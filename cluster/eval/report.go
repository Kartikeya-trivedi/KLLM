package eval

import (
	"fmt"
	"strings"
)

// table renders a Markdown table; the first column is left-aligned, the
// rest right-aligned.
func table(b *strings.Builder, header []string, rows [][]string) {
	b.WriteString("| " + strings.Join(header, " | ") + " |\n|")
	for i := range header {
		if i == 0 {
			b.WriteString("---|")
		} else {
			b.WriteString("--:|")
		}
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	b.WriteString("\n")
}

func pct(x float64) string { return fmt.Sprintf("%.1f", 100*x) }

// Markdown renders the sweep as a report: the tables the analysis in
// docs/CLUSTER.md is written from.
func (r Report) Markdown() string {
	s := r.Sweep
	var b strings.Builder
	fmt.Fprintf(&b, "# Robustness sweep\n\n")
	fmt.Fprintf(&b, "%d nodes, 1–%d adversaries, %d requests x %d seeds per condition (%d requests per cell). ",
		s.Nodes, s.MaxAdversaries, s.Requests, len(s.Seeds), s.Requests*len(s.Seeds))
	fmt.Fprintf(&b, "Honest replicas have lossiness cycling over 0.05/0.10/0.20; adversaries are noiseless.\n")
	fmt.Fprintf(&b, "All numbers are percentages unless a unit is given. Generated by `cmd/robusteval`; do not edit.\n\n")

	var strategies []string // wait-for-all methods, in sweep order
	var dispatched []Method
	for _, m := range s.Methods {
		switch {
		case isAblation(m.Aggregator):
		case m.PolicyName() == "all":
			strategies = append(strategies, m.String())
		default:
			dispatched = append(dispatched, m)
		}
	}
	cell := func(attack string, f int, method string, get func(Metrics) float64) string {
		if m, ok := r.Get(attack, f, method); ok {
			return pct(get(m))
		}
		return "–"
	}
	em := func(m Metrics) float64 { return m.ExactMatch }

	// Accuracy by strategy and attack, at each adversary count.
	for f := 1; f <= s.MaxAdversaries; f++ {
		fmt.Fprintf(&b, "## Exact match, %d of %d nodes adversarial\n\n", f, s.Nodes)
		header := append([]string{"strategy", "normal"}, s.Attacks...)
		var rows [][]string
		for _, st := range strategies {
			row := []string{st, cell("normal", 0, st, em)}
			for _, a := range s.Attacks {
				row = append(row, cell(a, f, st, em))
			}
			rows = append(rows, row)
		}
		table(&b, header, rows)
	}

	// Robustness summary.
	fmt.Fprintf(&b, "## Robustness summary\n\n")
	fmt.Fprintf(&b, "Worst case over all attacks at each adversary count, and the attack responsible. ")
	fmt.Fprintf(&b, "Breakdown is the smallest adversary count at which some attack takes exact match below 50%%.\n\n")
	header := []string{"strategy", "clean"}
	for f := 1; f <= s.MaxAdversaries; f++ {
		header = append(header, fmt.Sprintf("worst f=%d", f))
	}
	header = append(header, "breakdown")
	var rows [][]string
	for _, rb := range r.Robustness() {
		row := []string{rb.Method, pct(rb.Clean)}
		for i, w := range rb.Worst {
			row = append(row, fmt.Sprintf("%s (%s)", pct(w), rb.Hard[i]))
		}
		bd := fmt.Sprintf("> %d", s.MaxAdversaries)
		if rb.Breakdown > 0 {
			bd = fmt.Sprint(rb.Breakdown)
		}
		rows = append(rows, append(row, bd))
	}
	table(&b, header, rows)

	// Capture: cells where one seed tells a different story from the rest.
	minority := (s.Nodes - 1) / 2
	fmt.Fprintf(&b, "## Capture: runs that went wrong entirely\n\n")
	fmt.Fprintf(&b, "Cells, up to %d adversaries, where the best and worst seed differ by more than 30 points. ", minority)
	fmt.Fprintf(&b, "A pooled figure hides these: the strategy is not somewhat worse, it is right on most runs and captured on one.\n\n")
	rows = nil
	for _, m := range r.Metrics {
		if m.Adversaries <= minority && m.Policy == "all" && m.SeedMax-m.SeedMin > 0.3 {
			rows = append(rows, []string{m.Method, m.Attack, fmt.Sprint(m.Adversaries), pct(m.ExactMatch), pct(m.SeedMin), pct(m.SeedMax)})
		}
	}
	if len(rows) == 0 {
		b.WriteString("None.\n\n")
	} else {
		table(&b, []string{"strategy", "attack", "f", "pooled EM", "worst seed", "best seed"}, rows)
	}

	// Ablation of the adaptive strategy.
	var ablations []string
	for _, m := range s.Methods {
		if isAblation(m.Aggregator) && m.PolicyName() == "all" {
			ablations = append(ablations, m.String())
		}
	}
	if len(ablations) > 0 {
		fmt.Fprintf(&b, "## Ablation of the adaptive strategy, %d of %d nodes adversarial\n\n", minority, s.Nodes)
		fmt.Fprintf(&b, "Exact match with one defence removed (worst seed in brackets where it differs by more than 5 points).\n\n")
		header = append([]string{"variant"}, s.Attacks...)
		rows = nil
		for _, st := range append([]string{"token-vote", "adaptive"}, ablations...) {
			row := []string{st}
			for _, a := range s.Attacks {
				c, ok := r.Get(a, minority, st)
				switch {
				case !ok:
					row = append(row, "–")
				case c.ExactMatch-c.SeedMin > 0.05:
					row = append(row, fmt.Sprintf("%s [%s]", pct(c.ExactMatch), pct(c.SeedMin)))
				default:
					row = append(row, pct(c.ExactMatch))
				}
			}
			rows = append(rows, row)
		}
		table(&b, header, rows)
	}

	// Attack success.
	fmt.Fprintf(&b, "## Attack success rate, %d of %d nodes adversarial\n\n", minority, s.Nodes)
	fmt.Fprintf(&b, "Of the requests on which the adversaries submitted a tampered answer, how often that answer was returned.\n\n")
	header = append([]string{"strategy"}, s.Attacks...)
	rows = nil
	for _, st := range strategies {
		row := []string{st}
		for _, a := range s.Attacks {
			row = append(row, cell(a, minority, st, func(m Metrics) float64 { return m.AttackSuccess }))
		}
		rows = append(rows, row)
	}
	table(&b, header, rows)

	// Dispatch policies: what reliability costs.
	fmt.Fprintf(&b, "## Dispatch policies: reliability against cost\n\n")
	fmt.Fprintf(&b, "Latency and compute are measured with no adversary; the remaining columns show what each policy gives up under attack.\n\n")
	f2 := min(2, s.MaxAdversaries)
	header = []string{"method", "EM", "p50 ms", "p99 ms", "nodes asked", "tokens/answer",
		fmt.Sprintf("EM collude f=%d", f2), fmt.Sprintf("EM fast f=%d", f2), fmt.Sprintf("EM sleeper f=%d", minority),
		fmt.Sprintf("p99 ms straggler f=%d", f2), fmt.Sprintf("p99 ms crash f=%d", f2)}
	rows = nil
	shown := map[string]bool{}
	add := func(m Method) {
		name := m.String()
		if shown[name] {
			return
		}
		shown[name] = true
		c, ok := r.Get("normal", 0, name)
		if !ok {
			return
		}
		ms := func(attack string) string {
			if x, ok := r.Get(attack, f2, name); ok {
				return fmt.Sprintf("%.0f", x.LatencyP99)
			}
			return "–"
		}
		rows = append(rows, []string{name, pct(c.ExactMatch), fmt.Sprintf("%.0f", c.LatencyP50), fmt.Sprintf("%.0f", c.LatencyP99),
			fmt.Sprintf("%.2f", c.NodeCalls), fmt.Sprintf("%.1f", c.Tokens),
			cell("collude", f2, name, em), cell("fast", f2, name, em), cell("sleeper", minority, name, em),
			ms("straggler"), ms("crash")})
	}
	for _, m := range dispatched { // each policy next to its wait-for-all counterpart
		add(Method{Aggregator: m.Aggregator})
	}
	for _, m := range dispatched {
		add(m)
	}
	table(&b, header, rows)

	// Detection.
	fmt.Fprintf(&b, "## Detection\n\n")
	fmt.Fprintf(&b, "`response` is the stateless per-request detector against tampered responses; `suspect` adds the adaptive strategy's memory; ")
	fmt.Fprintf(&b, "`node` is the tracker's end-of-run verdict against the nodes that tampered. Time-to-detect is in requests after a node's first tampered answer.\n\n")
	header = []string{"attack", "f", "response P", "response R", "suspect P", "suspect R", "node P", "node R", "time to detect", "honest nodes suspected"}
	rows = nil
	for _, d := range r.Detection {
		if d.Attack != "normal" && d.Adversaries != f2 && d.Adversaries != minority {
			continue
		}
		rows = append(rows, []string{d.Attack, fmt.Sprint(d.Adversaries),
			pct(d.RespPrecision), pct(d.RespRecall), pct(d.SuspPrecision), pct(d.SuspRecall),
			pct(d.NodePrecision), pct(d.NodeRecall), fmt.Sprintf("%.1f", d.TimeToDetect),
			fmt.Sprintf("%.2f", float64(d.FalseSuspects)/float64(len(s.Seeds)))})
	}
	table(&b, header, rows)
	return b.String()
}
